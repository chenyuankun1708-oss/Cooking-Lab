export function applyM9BatchAOverride(recipe: Recipe): Recipe {
  const override = m9BatchAOverrides[recipe.slug];
  if (!override) return recipe;
  return {
    ...recipe,
    ...(override.name ? { name: override.name } : {}),
    ...(override.description ? { description: override.description } : {}),
    ...(override.taxonomy ? { taxonomy: override.taxonomy } : {}),
    heroImageId: `${recipe.slug}-hero`,
    publication: { status: "published" },
    steps: override.steps,
    principles: [...override.principles],
  };
}
